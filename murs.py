@dp.message()
async def buttons_handler(message: types.Message, state: FSMContext):
    text = message.text

    # Шар судьбы
    if text == "🔮 Шар судьбы":
        await message.answer("Мурся: Можешь задать свой вопрос 🔮")
        await state.set_state(FateStates.waiting_for_question)
        return

    # Совет от котиков
    if text == "🐾 Совет от котиков":
        phrase = random.choice(cat_advice)
        await message.answer(phrase + " 🐾", reply_markup=keyboard)
        return

    # Поддержка
    if text == "💖 Поддержка":
        phrase = random.choice(support_phrases)
        await message.answer(phrase + " 💖", reply_markup=keyboard)
        return

    # Письмо от Фариды
    if text == "✉️ Письмо от Фариды":
        phrase = random.choice(farida_letter)
        await message.answer(phrase + " 💌", reply_markup=keyboard)
        return

    # Факт о кошках
    if text == "🐱 Факт о кошках":
        fact = random.choice(cat_facts)
        gif = random.choice(cat_gifs)
        await message.answer_animation(gif, caption=fact + " 🐱", reply_markup=keyboard)
        return

    # Настроение
    if text == "🌈 Настроение":
        await message.answer("Какое у тебя настроение? (Счастлив / Грусть / Злой)", reply_markup=keyboard)
        return

    # Обработка ответа для Шара судьбы
    current_state = await state.get_state()
    if current_state == FateStates.waiting_for_question:
        reply = random.choice(fate_phrases)
        await message.answer(f"Мурся: {reply}", reply_markup=keyboard)
        await state.clear()
        return

    # Настроение
    if text in mood_responses:
           await message.answer(mood_responses[text], reply_markup=keyboard)
           return

    # Любое другое сообщение
    await message.answer("Выбери пункт меню!", reply_markup=keyboard)

# ===== АВТО-УВЕДОМЛЕНИЯ КАЖДЫЕ 4 ЧАСА =====
async def scheduled_notifications():
    while True:
        for chat_id in ADMIN_IDS:
            choice = random.choice(["fate", "advice", "support", "fact", "letter"])
            if choice == "fate":
                phrase = random.choice(fate_phrases)
                await bot.send_message(chat_id, f"🔮 Напоминание: {phrase}")
            elif choice == "advice":
                phrase = random.choice(cat_advice)
                await bot.send_message(chat_id, f"🐾 Совет: {phrase}")
            elif choice == "support":
                phrase = random.choice(support_phrases)
                await bot.send_message(chat_id, f"💖 Поддержка: {phrase}")
            elif choice == "fact":
                fact = random.choice(cat_facts)
                gif = random.choice(cat_gifs)
                await bot.send_animation(chat_id, gif, caption=f"🐱 Факт: {fact}")
            elif choice == "letter":
                for phrase in farida_letter:
                    await bot.send_message(chat_id, f"✉️ {phrase}")
        await asyncio.sleep(4 * 60 * 60)  # 4 часа

# ===== MAIN =====
async def main():
    print("Бот запущен...")
    asyncio.create_task(scheduled_notifications())
    await dp.start_polling(bot)

if __name__ == "__main__":
    asyncio.run(main())

